-- NX-025: proyek dan anggotanya (ARCHITECTURE.md B.3).
-- OWNER_ID, DEPARTMENT_ID, dan USER_ID berisi ID publik milik User Service (tanpa FK: tidak ada shared database).

CREATE TABLE PROJECTS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    CODE             VARCHAR2(20)              NOT NULL,  -- huruf besar (dinormalisasi di Domain)
    NAME             VARCHAR2(200)             NOT NULL,
    DESCRIPTION      VARCHAR2(2000),
    STATUS           VARCHAR2(20)              NOT NULL,  -- PLANNING | ACTIVE | ON_HOLD | COMPLETED | ARCHIVED
    START_DATE       DATE,
    END_DATE         DATE,
    OWNER_ID         RAW(16)                   NOT NULL,
    DEPARTMENT_ID    RAW(16),
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_PROJECTS PRIMARY KEY (ID),
    CONSTRAINT UX_PROJECTS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT CK_PROJECTS_STATUS CHECK (STATUS IN ('PLANNING', 'ACTIVE', 'ON_HOLD', 'COMPLETED', 'ARCHIVED')),
    CONSTRAINT CK_PROJECTS_DATES CHECK (START_DATE IS NULL OR END_DATE IS NULL OR START_DATE <= END_DATE),
    CONSTRAINT CK_PROJECTS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

-- Kode proyek unik per tenant untuk baris yang belum dihapus (proyek yang diarsipkan tetap memegang kodenya).
CREATE UNIQUE INDEX UX_PROJECTS_TNT_CODE ON PROJECTS (
    CASE WHEN IS_DELETED = 0 THEN TENANT_ID END,
    CASE WHEN IS_DELETED = 0 THEN CODE END);
CREATE INDEX IX_PROJECTS_TNT_STATUS ON PROJECTS (TENANT_ID, STATUS);
CREATE INDEX IX_PROJECTS_TNT_OWNER ON PROJECTS (TENANT_ID, OWNER_ID);
CREATE INDEX IX_PROJECTS_TNT_DEPARTMENT ON PROJECTS (TENANT_ID, DEPARTMENT_ID);

CREATE TABLE PROJECT_MEMBERS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    PROJECT_ID       NUMBER(19)                NOT NULL,
    USER_ID          RAW(16)                   NOT NULL,
    ROLE             VARCHAR2(20)              NOT NULL,  -- MANAGER | MEMBER | VIEWER
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_PROJECT_MEMBERS PRIMARY KEY (ID),
    CONSTRAINT UX_PROJECT_MEMBERS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_PROJECT_MEMBERS_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECTS (ID),
    CONSTRAINT CK_PROJECT_MEMBERS_ROLE CHECK (ROLE IN ('MANAGER', 'MEMBER', 'VIEWER')),
    CONSTRAINT CK_PROJECT_MEMBERS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

-- Satu user satu keanggotaan aktif per proyek; index diawali kolom FK (PROJECT_ID).
CREATE UNIQUE INDEX UX_PROJECT_MEMBERS_PROJECT_USER ON PROJECT_MEMBERS (
    CASE WHEN IS_DELETED = 0 THEN PROJECT_ID END,
    CASE WHEN IS_DELETED = 0 THEN USER_ID END);
CREATE INDEX IX_PROJECT_MEMBERS_PROJECT_ID ON PROJECT_MEMBERS (PROJECT_ID);
CREATE INDEX IX_PROJECT_MEMBERS_TNT_USER ON PROJECT_MEMBERS (TENANT_ID, USER_ID);
