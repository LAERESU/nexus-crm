-- NX-026: read model user milik User Service, diperbarui dari event UserCreated/UserUpdated/UserDeactivated
-- (CONTEXT.md bagian 3 poin 4). Dipakai untuk menampilkan nama anggota proyek dan menolak user nonaktif.

CREATE TABLE USER_REF (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    USER_ID          RAW(16)                   NOT NULL,  -- ID publik user di User Service
    EMAIL            VARCHAR2(320),                       -- kosong bila event pertama yang tiba adalah UserDeactivated
    FULL_NAME        VARCHAR2(200),
    IS_ACTIVE        NUMBER(1)   DEFAULT 1     NOT NULL,
    LAST_EVENT_AT    TIMESTAMP WITH TIME ZONE  NOT NULL,  -- event yang lebih lama dari ini diabaikan
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_USER_REF PRIMARY KEY (ID),
    CONSTRAINT UX_USER_REF_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UX_USER_REF_TNT_USER UNIQUE (TENANT_ID, USER_ID),
    CONSTRAINT CK_USER_REF_IS_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_USER_REF_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);
