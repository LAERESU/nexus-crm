-- NX-027: milestone proyek (ARCHITECTURE.md C.2). Tanggal jatuh tempo harus di dalam rentang tanggal proyek
-- (aturan di Domain; rentang proyek bisa kosong).

CREATE TABLE MILESTONES (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    PROJECT_ID       NUMBER(19)                NOT NULL,
    NAME             VARCHAR2(200)             NOT NULL,
    DESCRIPTION      VARCHAR2(2000),
    DUE_DATE         DATE                      NOT NULL,
    STATUS           VARCHAR2(20)              NOT NULL,  -- OPEN | COMPLETED
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_MILESTONES PRIMARY KEY (ID),
    CONSTRAINT UX_MILESTONES_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_MILESTONES_PROJECT FOREIGN KEY (PROJECT_ID) REFERENCES PROJECTS (ID),
    CONSTRAINT CK_MILESTONES_STATUS CHECK (STATUS IN ('OPEN', 'COMPLETED')),
    CONSTRAINT CK_MILESTONES_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

-- Index FK (diawali PROJECT_ID, juga dipakai mencari tanggal jatuh tempo paling awal/akhir per proyek) dan index
-- query utama daftar milestone yang diawali TENANT_ID (CONTEXT.md bagian 5).
CREATE INDEX IX_MILESTONES_PROJECT_DUE ON MILESTONES (PROJECT_ID, DUE_DATE);
CREATE INDEX IX_MILESTONES_TNT_PROJECT_DUE ON MILESTONES (TENANT_ID, PROJECT_ID, DUE_DATE);
