-- NX-012: tabel kredensial, refresh token, klien OAuth, dan riwayat login (ARCHITECTURE.md B.1, ADR-0006).

CREATE TABLE CREDENTIALS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    USER_ID          RAW(16)                   NOT NULL,  -- PUBLIC_ID user di User Service
    EMAIL            VARCHAR2(320)             NOT NULL,  -- huruf kecil; unik global (ADR-0006)
    PASSWORD_HASH    VARCHAR2(200)             NOT NULL,
    FAILED_ATTEMPTS  NUMBER(5)   DEFAULT 0     NOT NULL,
    FIRST_FAILED_AT  TIMESTAMP WITH TIME ZONE,
    LOCKED_UNTIL     TIMESTAMP WITH TIME ZONE,
    ROLES            VARCHAR2(1000),          -- sementara sampai User Service tersedia (ADR-0006)
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_CREDENTIALS PRIMARY KEY (ID),
    CONSTRAINT UX_CREDENTIALS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UX_CREDENTIALS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_CREDENTIALS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

CREATE UNIQUE INDEX UX_CREDENTIALS_TENANT_USER ON CREDENTIALS (TENANT_ID, USER_ID);

CREATE TABLE REFRESH_TOKENS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    CREDENTIAL_ID    NUMBER(19)                NOT NULL,
    TOKEN_HASH       VARCHAR2(64)              NOT NULL,  -- SHA-256 hex; token asli tidak pernah disimpan
    EXPIRES_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    REVOKED_AT       TIMESTAMP WITH TIME ZONE,
    REPLACED_BY_ID   NUMBER(19),
    DEVICE_INFO      VARCHAR2(500),
    CREATED_IP       VARCHAR2(45),
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_REFRESH_TOKENS PRIMARY KEY (ID),
    CONSTRAINT UX_REFRESH_TOKENS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UX_REFRESH_TOKENS_TOKEN_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_REFRESH_TOKENS_CREDENTIAL FOREIGN KEY (CREDENTIAL_ID) REFERENCES CREDENTIALS (ID),
    CONSTRAINT FK_REFRESH_TOKENS_REPLACED_BY FOREIGN KEY (REPLACED_BY_ID) REFERENCES REFRESH_TOKENS (ID),
    CONSTRAINT CK_REFRESH_TOKENS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

-- Index FK di Oracle harus diawali kolom FK agar tidak terjadi lock tabel anak.
CREATE INDEX IX_REFRESH_TOKENS_CREDENTIAL_ID ON REFRESH_TOKENS (CREDENTIAL_ID, EXPIRES_AT);
CREATE INDEX IX_REFRESH_TOKENS_REPLACED_BY_ID ON REFRESH_TOKENS (REPLACED_BY_ID);

CREATE TABLE CLIENTS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    CLIENT_ID        VARCHAR2(100)             NOT NULL,
    SECRET_HASH      VARCHAR2(200),
    REDIRECT_URIS    VARCHAR2(2000),
    SCOPES           VARCHAR2(1000),
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_CLIENTS PRIMARY KEY (ID),
    CONSTRAINT UX_CLIENTS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UX_CLIENTS_CLIENT_ID UNIQUE (CLIENT_ID),
    CONSTRAINT CK_CLIENTS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

CREATE INDEX IX_CLIENTS_TENANT_ID ON CLIENTS (TENANT_ID);

-- Riwayat percobaan login. Bila email tidak dikenal, TENANT_ID = 0 dan CREDENTIAL_ID kosong;
-- email yang dicoba sengaja tidak disimpan (data pribadi).
CREATE TABLE LOGIN_HISTORY (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)  DEFAULT 0     NOT NULL,
    CREDENTIAL_ID    NUMBER(19),
    SUCCEEDED        NUMBER(1)                 NOT NULL,
    FAILURE_REASON   VARCHAR2(50),
    IP_ADDRESS       VARCHAR2(45),
    USER_AGENT       VARCHAR2(500),
    OCCURRED_AT      TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_LOGIN_HISTORY PRIMARY KEY (ID),
    CONSTRAINT UX_LOGIN_HISTORY_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_LOGIN_HISTORY_CREDENTIAL FOREIGN KEY (CREDENTIAL_ID) REFERENCES CREDENTIALS (ID),
    CONSTRAINT CK_LOGIN_HISTORY_SUCCEEDED CHECK (SUCCEEDED IN (0, 1)),
    CONSTRAINT CK_LOGIN_HISTORY_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

CREATE INDEX IX_LOGIN_HISTORY_CREDENTIAL_ID ON LOGIN_HISTORY (CREDENTIAL_ID, OCCURRED_AT);
CREATE INDEX IX_LOGIN_HISTORY_TENANT_ID ON LOGIN_HISTORY (TENANT_ID, OCCURRED_AT);
