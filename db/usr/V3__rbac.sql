-- NX-019: role, permission, dan penugasan role ke user dengan scope (ARCHITECTURE.md B.2 dan G.2).
-- Isi PERMISSIONS dan role default diisi aplikasi saat startup (DefaultRoleSeeder) dari satu katalog di Domain,
-- sehingga permission baru cukup ditambahkan di kode tanpa migrasi data.

CREATE TABLE PERMISSIONS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)  DEFAULT 0     NOT NULL,  -- tidak dipakai: katalog permission bersifat global
    CODE             VARCHAR2(100)             NOT NULL,  -- modul.aksi, mis. project.read
    MODULE           VARCHAR2(50)              NOT NULL,
    DESCRIPTION      VARCHAR2(500),
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_PERMISSIONS PRIMARY KEY (ID),
    CONSTRAINT UX_PERMISSIONS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT CK_PERMISSIONS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

-- Unik hanya untuk baris belum dihapus (lihat catatan UX_DEPARTMENTS_TNT_CODE di V2).
CREATE UNIQUE INDEX UX_PERMISSIONS_CODE ON PERMISSIONS (CASE WHEN IS_DELETED = 0 THEN CODE END);

CREATE TABLE ROLES (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    CODE             VARCHAR2(50)              NOT NULL,  -- HURUF_BESAR_DAN_GARIS_BAWAH, mis. TENANT_ADMIN
    NAME             VARCHAR2(100)             NOT NULL,
    DESCRIPTION      VARCHAR2(500),
    IS_SYSTEM        NUMBER(1)   DEFAULT 0     NOT NULL,  -- role bawaan: tidak bisa diubah atau dihapus lewat API
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_ROLES PRIMARY KEY (ID),
    CONSTRAINT UX_ROLES_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_ROLES_TENANT FOREIGN KEY (TENANT_ID) REFERENCES TENANTS (ID),
    CONSTRAINT CK_ROLES_IS_SYSTEM CHECK (IS_SYSTEM IN (0, 1)),
    CONSTRAINT CK_ROLES_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

CREATE UNIQUE INDEX UX_ROLES_TNT_CODE ON ROLES (
    CASE WHEN IS_DELETED = 0 THEN TENANT_ID END,
    CASE WHEN IS_DELETED = 0 THEN CODE END);
CREATE INDEX IX_ROLES_TENANT_ID ON ROLES (TENANT_ID);

-- Baris ROLE_PERMISSIONS dan USER_ROLES dihapus sungguhan (data penghubung, bukan data bisnis), jadi unique biasa cukup.
CREATE TABLE ROLE_PERMISSIONS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    ROLE_ID          NUMBER(19)                NOT NULL,
    PERMISSION_ID    NUMBER(19)                NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_ROLE_PERMISSIONS PRIMARY KEY (ID),
    CONSTRAINT UX_ROLE_PERMISSIONS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UX_ROLE_PERMISSIONS_ROLE_PERM UNIQUE (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_ROLE_PERMISSIONS_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID),
    CONSTRAINT FK_ROLE_PERMISSIONS_PERMISSION FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSIONS (ID),
    CONSTRAINT CK_ROLE_PERMISSIONS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

CREATE INDEX IX_ROLE_PERMISSIONS_PERMISSION_ID ON ROLE_PERMISSIONS (PERMISSION_ID);

CREATE TABLE USER_ROLES (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    USER_ID          NUMBER(19)                NOT NULL,
    ROLE_ID          NUMBER(19)                NOT NULL,
    SCOPE_TYPE       VARCHAR2(20)              NOT NULL,  -- GLOBAL | DEPARTMENT | PROJECT
    SCOPE_ID         RAW(16),                             -- PUBLIC_ID departemen/proyek; kosong untuk GLOBAL
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_USER_ROLES PRIMARY KEY (ID),
    CONSTRAINT UX_USER_ROLES_PUBLIC_ID UNIQUE (PUBLIC_ID),
    -- Oracle menganggap (NULL) sama pada kolom unique gabungan, jadi penugasan GLOBAL ganda tetap ditolak.
    CONSTRAINT UX_USER_ROLES_ASSIGNMENT UNIQUE (USER_ID, ROLE_ID, SCOPE_TYPE, SCOPE_ID),
    CONSTRAINT FK_USER_ROLES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_USER_ROLES_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID),
    CONSTRAINT CK_USER_ROLES_SCOPE_TYPE CHECK (SCOPE_TYPE IN ('GLOBAL', 'DEPARTMENT', 'PROJECT')),
    CONSTRAINT CK_USER_ROLES_SCOPE CHECK (
        (SCOPE_TYPE = 'GLOBAL' AND SCOPE_ID IS NULL) OR (SCOPE_TYPE <> 'GLOBAL' AND SCOPE_ID IS NOT NULL)),
    CONSTRAINT CK_USER_ROLES_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

CREATE INDEX IX_USER_ROLES_ROLE_ID ON USER_ROLES (ROLE_ID);
CREATE INDEX IX_USER_ROLES_TNT_USER ON USER_ROLES (TENANT_ID, USER_ID);
