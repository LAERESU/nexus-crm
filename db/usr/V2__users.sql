-- NX-018: tenant, departemen, dan user (ARCHITECTURE.md B.2).

CREATE TABLE TENANTS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)  DEFAULT 0     NOT NULL,  -- tidak dipakai: tenant adalah akar isolasi (ID = tenant)
    CODE             VARCHAR2(50)              NOT NULL,
    NAME             VARCHAR2(200)             NOT NULL,
    IS_ACTIVE        NUMBER(1)   DEFAULT 1     NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_TENANTS PRIMARY KEY (ID),
    CONSTRAINT UX_TENANTS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UX_TENANTS_CODE UNIQUE (CODE),
    CONSTRAINT CK_TENANTS_IS_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_TENANTS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

CREATE TABLE DEPARTMENTS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    PARENT_ID        NUMBER(19),
    CODE             VARCHAR2(50)              NOT NULL,
    NAME             VARCHAR2(200)             NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_DEPARTMENTS PRIMARY KEY (ID),
    CONSTRAINT UX_DEPARTMENTS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_DEPARTMENTS_TENANT FOREIGN KEY (TENANT_ID) REFERENCES TENANTS (ID),
    CONSTRAINT FK_DEPARTMENTS_PARENT FOREIGN KEY (PARENT_ID) REFERENCES DEPARTMENTS (ID),
    CONSTRAINT CK_DEPARTMENTS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

-- Kode departemen unik per tenant; index FK diawali kolom FK agar tidak terjadi lock tabel anak.
CREATE UNIQUE INDEX UX_DEPARTMENTS_TNT_CODE ON DEPARTMENTS (TENANT_ID, CODE);
CREATE INDEX IX_DEPARTMENTS_PARENT_ID ON DEPARTMENTS (PARENT_ID);

CREATE TABLE USERS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    DEPARTMENT_ID    NUMBER(19),
    EMAIL            VARCHAR2(320)             NOT NULL,  -- huruf kecil (dinormalisasi di Domain)
    FULL_NAME        VARCHAR2(200)             NOT NULL,
    JOB_TITLE        VARCHAR2(200),
    STATUS           VARCHAR2(20)              NOT NULL,  -- ACTIVE | INACTIVE
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (ID),
    CONSTRAINT UX_USERS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_USERS_TENANT FOREIGN KEY (TENANT_ID) REFERENCES TENANTS (ID),
    CONSTRAINT FK_USERS_DEPARTMENT FOREIGN KEY (DEPARTMENT_ID) REFERENCES DEPARTMENTS (ID),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_USERS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

-- Email unik per tenant. EMAIL sudah huruf kecil, jadi index biasa cukup untuk case-insensitive.
CREATE UNIQUE INDEX UX_USERS_TNT_EMAIL ON USERS (TENANT_ID, EMAIL);
CREATE INDEX IX_USERS_TNT_DEPARTMENT ON USERS (TENANT_ID, DEPARTMENT_ID);
CREATE INDEX IX_USERS_DEPARTMENT_ID ON USERS (DEPARTMENT_ID);
