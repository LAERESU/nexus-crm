-- NX-033: riwayat perubahan status tugas (ARCHITECTURE.md C.4). Baris hanya ditambah, tidak pernah diubah.
-- CHANGED_BY berisi ID publik user milik User Service (tanpa FK: tidak ada shared database).

CREATE TABLE TASK_STATUS_HISTORY (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    TASK_ID          NUMBER(19)                NOT NULL,
    FROM_STATUS      VARCHAR2(20)              NOT NULL,
    TO_STATUS        VARCHAR2(20)              NOT NULL,
    CHANGED_BY       RAW(16)                   NOT NULL,
    CHANGED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_TASK_STATUS_HISTORY PRIMARY KEY (ID),
    CONSTRAINT UX_TASK_STATUS_HISTORY_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_TASK_STATUS_HISTORY_TASK FOREIGN KEY (TASK_ID) REFERENCES TASKS (ID),
    CONSTRAINT CK_TASK_STATUS_HISTORY_FROM CHECK (FROM_STATUS IN ('TODO', 'IN_PROGRESS', 'IN_REVIEW', 'BLOCKED', 'DONE', 'CANCELLED')),
    CONSTRAINT CK_TASK_STATUS_HISTORY_TO CHECK (TO_STATUS IN ('TODO', 'IN_PROGRESS', 'IN_REVIEW', 'BLOCKED', 'DONE', 'CANCELLED')),
    CONSTRAINT CK_TASK_STATUS_HISTORY_DELETED CHECK (IS_DELETED IN (0, 1))
);

-- Index FK sekaligus urutan riwayat satu tugas.
CREATE INDEX IX_TASK_STATUS_HISTORY_TASK_ID ON TASK_STATUS_HISTORY (TASK_ID, CHANGED_AT);
