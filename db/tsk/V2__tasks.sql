-- NX-032: tugas, assignee, dan read model proyek (ARCHITECTURE.md B.4, C.4).
-- PROJECT_ID, USER_ID, REPORTER_ID berisi ID publik milik Project/User Service (tanpa FK: tidak ada shared database).

CREATE TABLE TASKS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    PROJECT_ID       RAW(16)                   NOT NULL,
    PARENT_TASK_ID   NUMBER(19),                          -- subtask: maksimum satu tingkat (aturan Domain)
    TITLE            VARCHAR2(300 CHAR)        NOT NULL,
    DESCRIPTION      CLOB,
    STATUS           VARCHAR2(20)  DEFAULT 'TODO'   NOT NULL,
    PRIORITY         VARCHAR2(10)  DEFAULT 'MEDIUM' NOT NULL,
    DUE_DATE         DATE,
    REPORTER_ID      RAW(16)                   NOT NULL,
    COMPLETED_AT     TIMESTAMP WITH TIME ZONE,
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_TASKS PRIMARY KEY (ID),
    CONSTRAINT UX_TASKS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_TASKS_PARENT FOREIGN KEY (PARENT_TASK_ID) REFERENCES TASKS (ID),
    CONSTRAINT CK_TASKS_STATUS CHECK (STATUS IN ('TODO', 'IN_PROGRESS', 'IN_REVIEW', 'BLOCKED', 'DONE', 'CANCELLED')),
    CONSTRAINT CK_TASKS_PRIORITY CHECK (PRIORITY IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT CK_TASKS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

-- Index query utama (daftar tugas per proyek dan status) diawali TENANT_ID; index FK induk untuk subtask.
CREATE INDEX IX_TASKS_TNT_PRJ_STATUS ON TASKS (TENANT_ID, PROJECT_ID, STATUS);
CREATE INDEX IX_TASKS_PARENT_TASK_ID ON TASKS (PARENT_TASK_ID);

CREATE TABLE TASK_ASSIGNEES (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    TASK_ID          NUMBER(19)                NOT NULL,
    USER_ID          RAW(16)                   NOT NULL,
    ASSIGNED_AT      TIMESTAMP WITH TIME ZONE  NOT NULL,
    ASSIGNED_BY      RAW(16)                   NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_TASK_ASSIGNEES PRIMARY KEY (ID),
    CONSTRAINT UX_TASK_ASSIGNEES_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT FK_TASK_ASSIGNEES_TASK FOREIGN KEY (TASK_ID) REFERENCES TASKS (ID),
    CONSTRAINT CK_TASK_ASSIGNEES_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

CREATE UNIQUE INDEX UX_TASK_ASSIGNEES_TASK_USER ON TASK_ASSIGNEES (
    CASE WHEN IS_DELETED = 0 THEN TASK_ID END,
    CASE WHEN IS_DELETED = 0 THEN USER_ID END);
CREATE INDEX IX_TASK_ASSIGNEES_TASK_ID ON TASK_ASSIGNEES (TASK_ID);
CREATE INDEX IX_TASK_ASSIGNEES_USER ON TASK_ASSIGNEES (TENANT_ID, USER_ID);

-- Read model proyek dan anggotanya, diisi dari event Project Service (CONTEXT.md bagian 3 poin 4).
CREATE TABLE PROJECT_REF (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    PROJECT_ID       RAW(16)                   NOT NULL,
    CODE             VARCHAR2(20),                        -- kosong sampai ProjectCreated/ProjectUpdated tiba
    NAME             VARCHAR2(200),
    IS_ARCHIVED      NUMBER(1)   DEFAULT 0     NOT NULL,  -- tugas proyek arsip read-only
    DETAILS_EVENT_AT TIMESTAMP WITH TIME ZONE,            -- event lebih lama dari ini diabaikan
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_PROJECT_REF PRIMARY KEY (ID),
    CONSTRAINT UX_PROJECT_REF_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UX_PROJECT_REF_TNT_PROJECT UNIQUE (TENANT_ID, PROJECT_ID),
    CONSTRAINT CK_PROJECT_REF_IS_ARCHIVED CHECK (IS_ARCHIVED IN (0, 1)),
    CONSTRAINT CK_PROJECT_REF_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

CREATE TABLE PROJECT_MEMBER_REFS (
    ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_ID        RAW(16)                   DEFAULT SYS_GUID() NOT NULL,
    TENANT_ID        NUMBER(19)                NOT NULL,
    PROJECT_ID       RAW(16)                   NOT NULL,
    USER_ID          RAW(16)                   NOT NULL,
    PROJECT_ROLE     VARCHAR2(20)              NOT NULL,  -- MANAGER | MEMBER | VIEWER
    IS_REMOVED       NUMBER(1)   DEFAULT 0     NOT NULL,  -- baris dipertahankan agar urutan event bisa dinilai
    LAST_EVENT_AT    TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE  NOT NULL,
    CREATED_BY       NUMBER(19)                NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE,
    UPDATED_BY       NUMBER(19),
    ROW_VERSION      NUMBER(19)  DEFAULT 0     NOT NULL,
    IS_DELETED       NUMBER(1)   DEFAULT 0     NOT NULL,
    CONSTRAINT PK_PROJECT_MEMBER_REFS PRIMARY KEY (ID),
    CONSTRAINT UX_PROJECT_MEMBER_REFS_PUBLIC_ID UNIQUE (PUBLIC_ID),
    CONSTRAINT UX_PROJECT_MEMBER_REFS_MEMBER UNIQUE (TENANT_ID, PROJECT_ID, USER_ID),
    CONSTRAINT CK_PROJECT_MEMBER_REFS_ROLE CHECK (PROJECT_ROLE IN ('MANAGER', 'MEMBER', 'VIEWER')),
    CONSTRAINT CK_PROJECT_MEMBER_REFS_REMOVED CHECK (IS_REMOVED IN (0, 1)),
    CONSTRAINT CK_PROJECT_MEMBER_REFS_DELETED CHECK (IS_DELETED IN (0, 1))
);

-- Proyek yang diikuti seorang user (daftar tugas tanpa filter proyek).
CREATE INDEX IX_PROJECT_MEMBER_REFS_TNT_USER ON PROJECT_MEMBER_REFS (TENANT_ID, USER_ID);
